#!/bin/bash
# Certificates of the conversion broker and its workers (mutual TLS).
#
# They live in the "certs" volume (/certs):
#   ca.crt ca.key                 installation CA (the key never leaves the volume)
#   broker.crt broker.key         certificate of the broker
#   workers/<name>.crt|.key       one certificate per worker; CN = <name>
#
# Usage (from the MODIP directory):
#   docker compose run --rm certs ensure          CA, broker and the "local" worker
#   docker compose run --rm -T certs worker NAME > NAME.tar.gz
#                                                 bundle for a remote worker
#   docker compose run --rm certs list
#   docker compose run --rm certs renew-broker    after changing MODIP_CONVERSION_BROKER_HOSTS
#
# A worker also needs its name in MODIP_CONVERSION_WORKERS; removing it from
# there revokes it.
set -euo pipefail
umask 077

DIR=${MODIP_CERT_DIR:-/certs}
DAYS=${MODIP_CERT_DAYS:-3650}
PORT=${MODIP_CONVERSION_BROKER_PORT:-7443}
mkdir -p "$DIR/workers"

log() { echo "$*" >&2; }

valid_name() {
  [[ "$1" =~ ^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$ ]] || { log "invalid worker name: '$1' (letters, digits, . _ -)"; exit 2; }
  [ "$1" != conversion-broker ] || { log "'conversion-broker' is the name of the broker"; exit 2; }
}

ensure_ca() {
  [ -s "$DIR/ca.key" ] && [ -s "$DIR/ca.crt" ] && return
  log "creating the CA"
  openssl genrsa -out "$DIR/ca.key" 3072 2>/dev/null
  openssl req -x509 -new -sha256 -days "$DAYS" -key "$DIR/ca.key" -out "$DIR/ca.crt" \
    -subj "/O=MODIP/CN=MODIP conversion CA" 2>/dev/null
  chmod 644 "$DIR/ca.crt"
}

# sign NAME OUT_PREFIX EXTENDED_KEY_USAGE [SAN]
sign() {
  local name=$1 out=$2 usage=$3 san=${4:-}
  local ext
  ext=$(mktemp)
  {
    echo "basicConstraints=CA:FALSE"
    echo "keyUsage=digitalSignature,keyEncipherment"
    echo "extendedKeyUsage=$usage"
    [ -n "$san" ] && echo "subjectAltName=$san"
  } > "$ext"
  openssl genrsa -out "$out.key" 2048 2>/dev/null
  openssl req -new -sha256 -key "$out.key" -subj "/O=MODIP/CN=$name" -out "$out.csr" 2>/dev/null
  openssl x509 -req -sha256 -days "$DAYS" -in "$out.csr" -CA "$DIR/ca.crt" -CAkey "$DIR/ca.key" \
    -CAcreateserial -CAserial "$DIR/ca.srl" -extfile "$ext" -out "$out.crt" 2>/dev/null
  rm -f "$out.csr" "$ext"
  chmod 600 "$out.key"
  chmod 644 "$out.crt"
}

broker_san() {
  local san="DNS:conversion-broker,DNS:localhost,IP:127.0.0.1" host
  for host in ${MODIP_CONVERSION_BROKER_HOSTS//,/ }; do
    if [[ "$host" =~ ^[0-9.]+$ || "$host" == *:* ]]; then san="$san,IP:$host"; else san="$san,DNS:$host"; fi
  done
  echo "$san"
}

ensure_broker() {
  [ -s "$DIR/broker.key" ] && [ -s "$DIR/broker.crt" ] && return
  log "creating the broker certificate ($(broker_san))"
  sign conversion-broker "$DIR/broker" serverAuth "$(broker_san)"
}

ensure_worker() {
  valid_name "$1"
  [ -s "$DIR/workers/$1.key" ] && [ -s "$DIR/workers/$1.crt" ] && return
  log "creating the certificate of worker '$1'"
  sign "$1" "$DIR/workers/$1" clientAuth
}

case "${1:-ensure}" in
  ensure)
    ensure_ca
    ensure_broker
    ensure_worker local
    ;;
  renew-broker)
    ensure_ca
    rm -f "$DIR/broker.key" "$DIR/broker.crt"
    ensure_broker
    log "restart the broker: docker compose restart conversion-broker"
    ;;
  worker)
    name=${2:-}
    valid_name "$name"
    ensure_ca
    ensure_worker "$name"
    host=${MODIP_CONVERSION_PUBLIC_HOST:-}
    [ -n "$host" ] || log "warning: MODIP_CONVERSION_PUBLIC_HOST is empty; edit MODIP_BROKER_URI in .env.worker"
    bundle=$(mktemp -d)
    mkdir -p "$bundle/certs"
    cp "$DIR/ca.crt" "$bundle/certs/ca.crt"
    cp "$DIR/workers/$name.crt" "$bundle/certs/worker.crt"
    cp "$DIR/workers/$name.key" "$bundle/certs/worker.key"
    cat > "$bundle/.env.worker" <<ENV
# Conversion worker "$name" (generated by certs.sh)
MODIP_WORKER_NAME=$name
MODIP_BROKER_URI=drbssl://${host:-BROKER_HOST}:$PORT
ENV
    tar -C "$bundle" -czf - certs .env.worker
    rm -rf "$bundle"
    log "bundle for worker '$name' written; add it to MODIP_CONVERSION_WORKERS"
    ;;
  list)
    for crt in "$DIR/broker.crt" "$DIR"/workers/*.crt; do
      [ -s "$crt" ] || continue
      printf '%-40s %s\n' "$(openssl x509 -noout -subject -in "$crt" | sed 's/.*CN *= *//')" \
        "$(openssl x509 -noout -enddate -in "$crt" | sed 's/notAfter=/expires /')"
    done
    ;;
  *)
    log "usage: certs.sh ensure | worker NAME | list | renew-broker"
    exit 2
    ;;
esac
